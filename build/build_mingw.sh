#!/bin/sh
# Builds dist/<VERSION>/ddraw.dll (32-bit) with MinGW-w64 (i686-w64-mingw32).
# Also dist/<VERSION>/debug/ddraw.dll, the debug variant (test options). Reproducible: no link timestamp, so the same source gives the same SHA-1.
# Bump VERSION and add a CHANGELOG.md entry before building a new revision.
# An existing dist/<VERSION> is never overwritten. dist/ is not committed: tested builds go to
# GitHub Releases (private pre-releases until jayyanz approves a public release).
set -e
cd "$(dirname "$0")/.."
VER=$(tr -d ' \r\n' < VERSION)
OUT="dist/$VER"
if [ -e "$OUT/ddraw.dll" ]; then echo "dist/$VER already exists; bump VERSION first." >&2; exit 1; fi
VERRC=$(echo "$VER" | awk -F. '{printf "%d,%d,%d,0", $1, $2, $3}')
mkdir -p out "$OUT"
sh build/build_sdl3.sh
sed -e "s/@VER@/$VER/" -e "s/@VERRC@/$VERRC/" src/version.h > out/version.gen.h
i686-w64-mingw32-windres -I out -I src -o out/res.o src/ddraw_proxy.rc
# Release and debug variants (decisions log, 31 Oct 2026): the debug build adds the [Test] options RaceLogicRate,
# RateLog and CrashTest (the lines between ;@@debug-begin and ;@@debug-end in src/ddraw_proxy.ini).
# Each variant embeds its default ddraw_proxy.ini (for writing a missing file and updating old ones).
make_ini() {  # make_ini release|debug > file
    if [ "$1" = release ]; then
        awk '/^;@@debug-begin/{skip=1;next} /^;@@debug-end/{skip=0;next} !skip' src/ddraw_proxy.ini
    else
        grep -v '^;@@debug-' src/ddraw_proxy.ini
    fi | sed "s/@VER@/$VER/"
}
build_variant() {  # build_variant release|debug <dir> [extra flags]
    v=$1; d=$2; shift 2
    mkdir -p "$d"
    make_ini "$v" > "$d/ddraw_proxy.ini"
    { echo '/* Generated by build_mingw.sh from src/ddraw_proxy.ini. Do not edit. */'
      echo 'static const char kDefaultIni[] ='
      awk '{ sub(/\r$/, ""); gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); print "    \"" $0 "\\n\"" }' "$d/ddraw_proxy.ini"
      echo '    ;'; } > out/ini_default.gen.h
    i686-w64-mingw32-g++-win32 -std=c++17 -O2 -Wall -s -shared -static-libgcc -static-libstdc++ -static -Wl,--no-insert-timestamp -include out/version.gen.h -I src -I out -I out/sdl3/include "$@" \
        -o "$d/ddraw.dll" src/ddraw_proxy.cpp src/cdaudio_emu.cpp src/trace.cpp src/ddraw_own.cpp src/present_d3d11.cpp src/input_sdl.cpp src/options_menu.cpp src/hardening.cpp src/draw_distance.cpp src/pause_menu.cpp src/main_menu.cpp src/cheats.cpp out/res.o src/ddraw.def -Lout/sdl3/lib -lSDL3 -lsetupapi -limm32 -lole32 -loleaut32 -lversion -lpsapi -ladvapi32 -lshell32 -luser32 -lgdi32 -lkernel32 -lwinmm -luuid
}
build_variant release "$OUT"
build_variant debug "$OUT/debug" -DULT_DEBUG
sha1sum "$OUT/ddraw.dll" "$OUT/debug/ddraw.dll" | tee "$OUT/SHA1.txt"
sh build/build_installer.sh
